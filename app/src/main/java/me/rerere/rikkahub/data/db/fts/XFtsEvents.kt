package me.rerere.rikkahub.data.db.fts

/**
 * 全文检索域的**事件名常量**（与 `XStorageEvents` 同样的作用）。
 *
 * ## 为什么要集中而不是就地写字符串
 *
 * 事件名是**排查时的检索键** —— 用户复制一段诊断发给开发者，靠的就是在文本里定位
 * `fts.index.update` 这样的词。一旦散落成字面量，就会出现同一件事几种写法并存，
 * 日志再也搜不干净。
 */
object XFtsEvents {

    /**
     * 索引维护：本次保存实际改了几行。
     *
     * 这条是「**增量是否生效**」的现场证据 —— 它是**唯一**能把「只写了 1 行」
     * 这件事从设备上取证出来的记录（单测只证明了计划算得对，没证明**接线**连上了）。
     *
     * 读法：`已索引` 是规模，`需写入` 是本次实际改动。
     * 流式保存时**需写入通常只有 1**（那条正在增长的消息），
     * 而改动前这里是整个会话的行数。
     */
    const val INDEX_UPDATE = "fts.index.update"

    /** 全部事件名，供单测核对（新增事件须登记到这里）。 */
    val ALL: List<String> = listOf(INDEX_UPDATE)
}
